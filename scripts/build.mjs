const selected = { ...presenterIcons };
for (const name of names) {
  const key = name[0].toLowerCase() + name.slice(1);
  selected[key] = {
    name: name
      .replace(/[a-z0-9][A-Z]/g, (s) => s[0] + "-" + s[1])
      .toLowerCase(),
    body: icons[name]
      .map(
        ([tag, attrs]) =>
          `<${tag} ${Object.entries(attrs)
            .map(([k, v]) => `${k}="${enc(v)}"`)
            .join(" ")}/>`,
      )
      .join(""),
  };
}
fs.writeFileSync(
  path.join(buildDir, "icons.js"),
  `/* Lucide icons.\n${lucideLicense}\n*/\n// Generated by scripts/build.mjs.\nexport const icons=${JSON.stringify(selected)};\nexport const icon=(name,cls='')=>{const i=icons[name];return \`<svg class="lucide \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${i.body}</svg>\`;};\n`,
);
