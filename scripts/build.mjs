import fs from "node:fs";
import path from "node:path";
import katex from "katex";
import { createDeck } from "../presentations/areal/deck.mjs";
import { icons } from "lucide/dist/esm/lucide.js";
import { presenterIcons, lucideLicense } from "./icons.mjs";
const root = path.resolve(import.meta.dirname, "..");
const source = path.join(root, "presentations/areal");
const buildDir = path.join(root, "work/build");
const dir = path.join(buildDir, "presentations/areal");
fs.rmSync(buildDir, { recursive: true, force: true });
fs.mkdirSync(dir, { recursive: true });
fs.cpSync(path.join(source, "assets"), path.join(dir, "assets"), {
  recursive: true,
});
const enc = (s) =>
  String(s)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
const asset = (p) => p;
const math = (t, cls = "") =>
  `<div class="math ${cls}" data-tex="${enc(t)}">${katex.renderToString(t, { displayMode: true, throwOnError: true, output: "htmlAndMathml" })}</div>`;
const link = (u, t) => `<a href="${u}" target="_blank" rel="noopener">${t}</a>`;
const { slides, SRC } = createDeck({
  logo: "assets/brand/areal.png",
  antBlue: "assets/brand/ant-blue.png",
  antWhite: "assets/brand/ant-white.png",
  asset,
  math,
  enc,
  link,
});
const notes = Object.fromEntries(
  Object.entries(slides).map(([n, s]) => [
    n,
    {
      title: s.title,
      notes: s.notes,
      refs: s.refs.map((id) => SRC[id]),
      figures: s.figures || [],
    },
  ]),
);
const katexDist = new URL(".", import.meta.resolve("katex"));
fs.cpSync(new URL("fonts", katexDist), path.join(dir, "assets/fonts"), {
  recursive: true,
});
const katexLicense = fs.readFileSync(
  new URL("../LICENSE", import.meta.resolve("katex")),
  "utf8",
);
let css =
  "/* KaTeX MIT License\n" +
  katexLicense +
  "\n*/\n" +
  fs
    .readFileSync(new URL("katex.min.css", katexDist), "utf8")
    .replaceAll("url(fonts/", "url(assets/fonts/");
for (const name of ["foundation", "slides", "training"])
  css +=
    "\n" + fs.readFileSync(path.join(source, `styles/${name}.css`), "utf8");
css = css
  .replace("__BG__", "assets/brand/slide-background.png")
  .replace("__SECTION_BG__", "assets/brand/section-background.png");
fs.writeFileSync(
  path.join(dir, "content.html"),
  Object.values(slides)
    .map((s) => s.html)
    .join("\n"),
);
fs.writeFileSync(path.join(dir, "styles.css"), css);
fs.writeFileSync(path.join(dir, "notes.json"), JSON.stringify(notes, null, 2));
fs.writeFileSync(
  path.join(dir, "metadata.json"),
  JSON.stringify(
    {
      ...JSON.parse(
        fs.readFileSync(path.join(source, "metadata.json"), "utf8"),
      ),
      slideCount: Object.keys(slides).length,
    },
    null,
    2,
  ),
);
